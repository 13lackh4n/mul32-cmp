#!/usr/bin/env bash
# ----------------------------------------------------------------------------
# run_all.sh - regenerate vectors, verify every module, implement every module.
#
#   scripts/run_all.sh [vectors] [sim] [impl] [summary]   (default: all four)
#
# Everything runs strictly sequentially (parallel Vivado launches on this
# machine produced spurious tool errors).
#
#   vectors  python tb/golden.py
#   sim      full 10^6-vector runs, both signedness modes, every module
#            (log: build/sim/<tag>/sim.log, summary: reports/sim_summary.txt)
#   impl     scripts/synth.tcl fmax search per module (SIGNED_MODE=0), then
#            one extra implementation at 10.000 ns for power at a common
#            100 MHz clock -> reports/<name>_power_100MHz.rpt
#            (log: build/impl/<name>.log)
#   summary  python scripts/make_summary.py -> reports/summary.md
# ----------------------------------------------------------------------------
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
VIVADO_BIN="${VIVADO_BIN:-/c/Xilinx/2025.1.1/Vivado/bin}"
export PATH="$VIVADO_BIN:$PATH"
if command -v vivado.bat >/dev/null 2>&1; then VIVADO=vivado.bat; else VIVADO=vivado; fi
native() { if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else echo "$1"; fi; }
R="$(native "$ROOT")"

STAGES=("$@"); [[ ${#STAGES[@]} -eq 0 ]] && STAGES=(vectors sim impl summary)
want() { local s; for s in "${STAGES[@]}"; do [[ "$s" == "$1" ]] && return 0; done; return 1; }

# name | top | rtl | generics (name value ...) | PIPE_STAGES | tb plusargs
CONFIGS=(
  "mult_behav|mult_behav|rtl/mult_behav.v||2|"
  "mult_shiftadd|mult_shiftadd|rtl/mult_shiftadd.v||2|+WAIT +LATENCY=33"
  "mult_karatsuba|mult_karatsuba|rtl/mult_karatsuba.v||4|"
  "mult_wallace_b0|mult_wallace|rtl/mult_wallace.v|USE_BOOTH 0|4|"
  "mult_wallace_b1|mult_wallace|rtl/mult_wallace.v|USE_BOOTH 1|4|"
)

fail=0

if want vectors; then
    echo "== vectors"
    python -I tb/golden.py || exit 1
fi

if want sim; then
    echo "== simulation (full vector sets)"
    SUMMARY=reports/sim_summary.txt
    mkdir -p reports
    {
        echo "# Full-vector simulation results (tb/tb_mult32.v, Vivado xsim)"
        echo "# generated by scripts/run_all.sh on $(date '+%Y-%m-%d %H:%M')"
        echo "# vectors: vectors/vec_{unsigned,signed}.hex (400 directed + 1,000,000 random)"
        echo "# mult_shiftadd runs with +WAIT (one operation at a time); all others stream"
        echo "# with random idle cycles (+BUBBLE default 10%), i.e. mostly back-to-back."
        echo "# latency = cycles from the valid_in sample to the valid_out sample,"
        echo "# checked on every vector against +LATENCY."
    } > "$SUMMARY"
    for c in "${CONFIGS[@]}"; do
        IFS='|' read -r name top rtl gens ps plus <<< "$c"
        extra=""
        if [[ -n "$gens" ]]; then
            set -- $gens; extra=".$1($2)"
        fi
        for sm in 0 1; do
            vec=vectors/vec_unsigned.hex; [[ $sm == 1 ]] && vec=vectors/vec_signed.hex
            lat="+LATENCY=$ps"; [[ "$plus" == *LATENCY* ]] && lat=""
            tag="full_${name}_s${sm}"
            args=(-m "$top" -f "$rtl" -s "$sm" -p "$ps" -v "$vec" -t "$tag")
            [[ -n "$extra" ]] && args+=(-x "$extra")
            if scripts/sim.sh "${args[@]}" -- $plus $lat >/dev/null 2>&1; then r=PASS; else r=FAIL; fail=1; fi
            line="$tag: $r | $(grep -E '^ +(results|latency|mismatches|protocol errs) ' build/sim/$tag/sim.log | tr -s ' ' | tr '\n' ';')"
            echo "  $line"; echo "$line" >> "$SUMMARY"
        done
    done
fi

if want impl; then
    echo "== implementation + fmax search (SIGNED_MODE=0)"
    for c in "${CONFIGS[@]}"; do
        IFS='|' read -r name top rtl gens ps plus <<< "$c"
        mkdir -p build/impl
        echo "  $name: started $(date +%H:%M:%S)"
        (cd build/impl && "$VIVADO" -mode batch -nojournal -log "$name.log" \
            -source "$R/scripts/synth.tcl" \
            -tclargs "$name" "$top" "$R/$rtl" SIGNED_MODE 0 PIPE_STAGES "$ps" $gens \
            >/dev/null 2>&1)
        res=$(grep -h '^FMAX-RESULT' "build/impl/$name.log")
        [[ -n "$res" ]] || { echo "  $name: FAILED (see build/impl/$name.log)"; fail=1; continue; }
        echo "  $res"

        # Power at a common 100 MHz clock
        (cd build/impl && FMAX_SINGLE=10.0 "$VIVADO" -mode batch -nojournal \
            -log "${name}_100MHz.log" -source "$R/scripts/synth.tcl" \
            -tclargs "${name}_100MHz" "$top" "$R/$rtl" SIGNED_MODE 0 PIPE_STAGES "$ps" $gens \
            >/dev/null 2>&1)
        if [[ -f "build/impl/${name}_100MHz/T10.000/power.rpt" ]]; then
            cp "build/impl/${name}_100MHz/T10.000/power.rpt" "reports/${name}_power_100MHz.rpt"
            echo "  $(grep -h '^FMAX-SINGLE' "build/impl/${name}_100MHz.log")"
        else
            echo "  $name: 100 MHz power run FAILED"; fail=1
        fi
    done
fi

if want summary; then
    echo "== summary"
    python -I scripts/make_summary.py || fail=1
fi

exit $fail
